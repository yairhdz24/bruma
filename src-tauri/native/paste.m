#import <AppKit/AppKit.h>
#import <ApplicationServices/ApplicationServices.h>
#include <stdlib.h>
#include <string.h>
#include <unistd.h>

// "name\nbundle\npid" for the app that has keyboard focus. Call on the main thread.
char *bruma_frontmost_app(void) {
    @autoreleasepool {
        @try {
            NSRunningApplication *app = NSWorkspace.sharedWorkspace.frontmostApplication;
            if (app == nil) return NULL;
            NSString *name = app.localizedName ?: @"";
            NSString *bundle = app.bundleIdentifier ?: @"";
            name = [[name componentsSeparatedByCharactersInSet:NSCharacterSet.newlineCharacterSet] componentsJoinedByString:@" "];
            NSString *line = [NSString stringWithFormat:@"%@\n%@\n%d", name, bundle, app.processIdentifier];
            return strdup(line.UTF8String);
        } @catch (NSException *exception) { (void)exception; return NULL; }
    }
}

static void post_command_key(CGKeyCode key) {
    // A private source plus explicit flags keeps a still-held Control or fn (from the shortcut) out of the keystroke.
    CGEventSourceRef source = CGEventSourceCreate(kCGEventSourceStatePrivate);
    CGEventRef down = CGEventCreateKeyboardEvent(source, key, true);
    CGEventRef up = CGEventCreateKeyboardEvent(source, key, false);
    CGEventSetFlags(down, kCGEventFlagMaskCommand);
    CGEventSetFlags(up, kCGEventFlagMaskCommand);
    CGEventPost(kCGHIDEventTap, down);
    CGEventPost(kCGHIDEventTap, up);
    CFRelease(down); CFRelease(up);
    if (source) CFRelease(source);
}
static void post_command_v(void) { post_command_key((CGKeyCode)9); }  // kVK_ANSI_V

static NSMutableArray<NSPasteboardItem *> *snapshot(NSPasteboard *board) {
    NSMutableArray<NSPasteboardItem *> *saved = [NSMutableArray array];
    for (NSPasteboardItem *item in board.pasteboardItems ?: @[]) {
        NSPasteboardItem *copy = [[NSPasteboardItem alloc] init];
        BOOL any = NO;
        for (NSPasteboardType type in item.types) {
            NSData *data = [item dataForType:type];
            if (data != nil) { [copy setData:data forType:type]; any = YES; }
        }
        if (any) [saved addObject:copy];
    }
    return saved;
}

// Puts `utf8` on the clipboard and, when allowed, presses ⌘V in the focused app.
// The previous clipboard (every item and type: images, files, rich text) is restored
// afterwards unless something else changed the clipboard in the meantime.
//  0 = pasted, 1 = Accessibility missing (text left on the clipboard), 2 = copy only requested, -1 = invalid input.
int bruma_paste_text(const char *utf8, int paste, int restore_after_ms) {
    @autoreleasepool {
        if (utf8 == NULL) return -1;
        NSString *text = [NSString stringWithUTF8String:utf8];
        if (text == nil || text.length == 0) return -1;
        BOOL trusted = AXIsProcessTrusted();
        BOOL willPaste = paste && trusted;
        NSPasteboard *board = NSPasteboard.generalPasteboard;

        NSMutableArray<NSPasteboardItem *> *saved = willPaste ? snapshot(board) : [NSMutableArray array];

        [board clearContents];
        NSMutableArray<NSPasteboardType> *types = [NSMutableArray arrayWithObject:NSPasteboardTypeString];
        // Clipboard managers that honour these markers skip our temporary payload.
        if (willPaste) { [types addObject:@"org.nspasteboard.TransientType"]; [types addObject:@"org.nspasteboard.AutoGeneratedType"]; [types addObject:@"org.nspasteboard.ConcealedType"]; }
        [board declareTypes:types owner:nil];
        [board setString:text forType:NSPasteboardTypeString];
        if (willPaste) {
            [board setData:[NSData data] forType:@"org.nspasteboard.TransientType"];
            [board setData:[NSData data] forType:@"org.nspasteboard.AutoGeneratedType"];
            [board setData:[NSData data] forType:@"org.nspasteboard.ConcealedType"];
        }
        NSInteger ours = board.changeCount;
        if (!willPaste) return paste ? 1 : 2;

        post_command_v();
        usleep((useconds_t)MAX(150, MIN(restore_after_ms, 2000)) * 1000);
        if (board.changeCount == ours) {
            [board clearContents];
            if (saved.count > 0) [board writeObjects:saved];
        }
        return 0;
    }
}

// Copies the current selection of the focused app with ⌘C and returns it, then puts the
// previous clipboard back. Used only when Accessibility cannot read the selection directly
// (some web views). NULL when nothing was selected or the app ignored ⌘C.
char *bruma_copy_selection(int wait_ms) {
    @autoreleasepool {
        if (!AXIsProcessTrusted()) return NULL;
        NSPasteboard *board = NSPasteboard.generalPasteboard;
        NSMutableArray<NSPasteboardItem *> *saved = snapshot(board);
        NSInteger before = board.changeCount;
        post_command_key((CGKeyCode)8);  // kVK_ANSI_C
        NSString *text = nil;
        int waited = 0, limit = MAX(100, MIN(wait_ms, 1500));
        while (waited < limit) {
            usleep(25 * 1000); waited += 25;
            if (board.changeCount != before) { usleep(30 * 1000); text = [board stringForType:NSPasteboardTypeString]; break; }
        }
        if (board.changeCount != before) {
            [board clearContents];
            if (saved.count > 0) [board writeObjects:saved];
        }
        if (text.length == 0) return NULL;
        return strdup(text.UTF8String);
    }
}

// Remembers the last app that was frontmost before Bruma, so a click on the floating pill
// (which activates Bruma) can still paste into the app the user was working in.
static pid_t lastExternalPid = 0;
static NSString *lastExternalName = nil;
static NSString *lastExternalBundle = nil;
static id activationObserver = nil;

static void remember(NSRunningApplication *app) {
    if (app == nil || app.processIdentifier == NSProcessInfo.processInfo.processIdentifier) return;
    @synchronized ([NSWorkspace class]) {
        lastExternalPid = app.processIdentifier;
        lastExternalName = [app.localizedName copy] ?: @"";
        lastExternalBundle = [app.bundleIdentifier copy] ?: @"";
    }
}

// Call once on the main thread.
void bruma_track_frontmost_start(void) {
    @autoreleasepool {
        if (activationObserver != nil) return;
        remember(NSWorkspace.sharedWorkspace.frontmostApplication);
        activationObserver = [NSWorkspace.sharedWorkspace.notificationCenter
            addObserverForName:NSWorkspaceDidActivateApplicationNotification object:nil queue:NSOperationQueue.mainQueue
            usingBlock:^(NSNotification *note) { remember(note.userInfo[NSWorkspaceApplicationKey]); }];
    }
}

// "name\nbundle\npid" of the last external app, or NULL.
char *bruma_last_external_app(void) {
    @autoreleasepool {
        @synchronized ([NSWorkspace class]) {
            if (lastExternalPid <= 0) return NULL;
            NSRunningApplication *app = [NSRunningApplication runningApplicationWithProcessIdentifier:lastExternalPid];
            if (app == nil || app.terminated) return NULL;
            NSString *name = [[lastExternalName componentsSeparatedByCharactersInSet:NSCharacterSet.newlineCharacterSet] componentsJoinedByString:@" "];
            return strdup([NSString stringWithFormat:@"%@\n%@\n%d", name, lastExternalBundle, lastExternalPid].UTF8String);
        }
    }
}

// Brings `pid` to the front and waits up to ~600 ms for it. 1 = frontmost, 0 = not.
int bruma_activate_app(int pid) {
    @autoreleasepool {
        NSRunningApplication *app = [NSRunningApplication runningApplicationWithProcessIdentifier:(pid_t)pid];
        if (app == nil || app.terminated) return 0;
#pragma clang diagnostic push
#pragma clang diagnostic ignored "-Wdeprecated-declarations"
        // Bruma is the active app at this point, so macOS lets it hand activation back.
        [app activateWithOptions:NSApplicationActivateIgnoringOtherApps];
#pragma clang diagnostic pop
        for (int i = 0; i < 30; i++) {
            if (NSWorkspace.sharedWorkspace.frontmostApplication.processIdentifier == (pid_t)pid) { usleep(60 * 1000); return 1; }
            usleep(20 * 1000);
        }
        return 0;
    }
}
